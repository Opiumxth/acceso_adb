-- NUCLEO
create table escuelas (
    id_escuela  number(4)      not null,
    nombre      varchar2(100)  not null,
    facultad    varchar2(100)  not null,
    constraint  pk_escuelas     primary key (id_escuela),
    constraint  uq_escuelas_nombre unique (nombre)
);

create table personas (
    id_persona      number generated by default as identity (start with 1000),
    codigo          char(8)        not null,  -- contenido del QR
    nombre          varchar2(100)  not null,
    dni             char(8)        not null,
    correo          varchar2(100),
    tipo            varchar2(15)   not null,
    estado          varchar2(12)   default 'activo' not null,
    fecha_registro  timestamp      default systimestamp not null,
    constraint pk_personas        primary key (id_persona),
    constraint uq_personas_codigo unique (codigo),
    constraint uq_personas_dni    unique (dni),
    constraint ck_personas_tipo   check (tipo in
        ('estudiante', 'docente', 'visitante', 'vigilante', 'administrativo')),
    constraint ck_personas_estado check (estado in
        ('activo', 'inactivo', 'suspendido'))
);

create table estudiantes (
    id_estudiante  number        not null,
    id_escuela     number(4)     not null,
    ciclo          number(2)     not null,
    constraint pk_estudiantes         primary key (id_estudiante),
    constraint fk_estudiantes_persona foreign key (id_estudiante)
        references personas (id_persona),
    constraint fk_estudiantes_escuela foreign key (id_escuela)
        references escuelas (id_escuela),
    constraint ck_estudiantes_ciclo   check (ciclo between 1 and 12)
);

create table docentes (
    id_docente    number         not null,
    especialidad  varchar2(100),
    constraint pk_docentes         primary key (id_docente),
    constraint fk_docentes_persona foreign key (id_docente)
        references personas (id_persona)
);

create table zonas (
    id_zona  number(4)      not null,
    nombre   varchar2(80)   not null,
    tipo     varchar2(15)   not null,
    aforo    number(5),
    constraint pk_zonas        primary key (id_zona),
    constraint uq_zonas_nombre unique (nombre),
    constraint ck_zonas_tipo   check (tipo in
        ('puerta', 'aula', 'laboratorio', 'biblioteca', 'administrativa')),
    constraint ck_zonas_aforo  check (aforo is null or aforo > 0)
);

create table puntos_control (
    id_punto  number(4)      not null,
    id_zona   number(4)      not null,
    nombre    varchar2(80)   not null,
    sentido   varchar2(10)   default 'mixto' not null,
    estado    varchar2(10)   default 'activo' not null,
    constraint pk_puntos_control primary key (id_punto),
    constraint fk_puntos_zona    foreign key (id_zona) references zonas (id_zona),
    constraint ck_puntos_sentido check (sentido in ('entrada', 'salida', 'mixto')),
    constraint ck_puntos_estado  check (estado in ('activo', 'inactivo'))
);

-- id_persona es nulo cuando el codigo leido no existe en personas
create table accesos (
    id_acceso     number generated by default as identity (start with 1000),
    id_persona    number,
    codigo_leido  varchar2(20)   not null,
    id_punto      number(4)      not null,
    fecha_hora    timestamp      default systimestamp not null,
    resultado     varchar2(10)   not null,
    motivo        varchar2(40),
    metodo        varchar2(12)   default 'qr_rostro' not null,
    confianza     number(6,2),
    constraint pk_accesos         primary key (id_acceso),
    constraint fk_accesos_persona foreign key (id_persona)
        references personas (id_persona),
    constraint fk_accesos_punto   foreign key (id_punto)
        references puntos_control (id_punto),
    constraint ck_accesos_resultado check (resultado in ('permitido', 'denegado')),
    constraint ck_accesos_metodo    check (metodo in
        ('qr_rostro', 'manual', 'simulado'))
) tablespace ts_acceso_log;

-- ACADEMICO
create table cursos (
    id_curso    number(6)      not null,
    codigo      varchar2(10)   not null,
    nombre      varchar2(100)  not null,
    id_escuela  number(4)      not null,
    creditos    number(1)      not null,
    constraint pk_cursos         primary key (id_curso),
    constraint uq_cursos_codigo  unique (codigo),
    constraint fk_cursos_escuela foreign key (id_escuela)
        references escuelas (id_escuela),
    constraint ck_cursos_creditos check (creditos between 1 and 6)
);

-- id_aula apunta a la zona (aula o laboratorio) donde se dicta la seccion
create table secciones (
    id_seccion  number(6)     not null,
    id_curso    number(6)     not null,
    id_docente  number        not null,
    id_aula     number(4)     not null,
    periodo     varchar2(10)  not null,
    grupo       varchar2(3)   not null,
    cupo        number(3)     not null,
    constraint pk_secciones          primary key (id_seccion),
    constraint fk_secciones_curso    foreign key (id_curso)
        references cursos (id_curso),
    constraint fk_secciones_docente  foreign key (id_docente)
        references docentes (id_docente),
    constraint fk_secciones_aula     foreign key (id_aula)
        references zonas (id_zona),
    constraint uq_secciones_cpg      unique (id_curso, periodo, grupo),
    constraint ck_secciones_cupo     check (cupo > 0)
);

-- matricula de un estudiante en una seccion
create table inscripciones (
    id_seccion     number(6)    not null,
    id_estudiante  number       not null,
    faltas         number(3)    default 0 not null,
    estado         varchar2(12) default 'activa' not null,
    constraint pk_inscripciones            primary key (id_seccion, id_estudiante),
    constraint fk_inscripciones_seccion    foreign key (id_seccion)
        references secciones (id_seccion),
    constraint fk_inscripciones_estudiante foreign key (id_estudiante)
        references estudiantes (id_estudiante),
    constraint ck_inscripciones_faltas     check (faltas >= 0),
    constraint ck_inscripciones_estado     check (estado in
        ('activa', 'inhabilitado', 'retirado'))
);

-- sesiones = clases dictadas de una seccion
create table sesiones (
    id_sesion    number generated by default as identity (start with 1000),
    id_seccion   number(6)    not null,
    hora_inicio  timestamp    not null,
    hora_fin     timestamp    not null,
    estado       varchar2(10) default 'programada' not null,
    constraint pk_sesiones         primary key (id_sesion),
    constraint fk_sesiones_seccion foreign key (id_seccion)
        references secciones (id_seccion),
    constraint ck_sesiones_horas   check (hora_fin > hora_inicio),
    constraint ck_sesiones_estado  check (estado in
        ('programada', 'en_curso', 'cerrada'))
);

create table asistencias (
    id_sesion      number       not null,
    id_estudiante  number       not null,
    estado         varchar2(10) not null,
    hora_registro  timestamp,
    id_acceso      number,
    constraint pk_asistencias            primary key (id_sesion, id_estudiante),
    constraint fk_asistencias_sesion     foreign key (id_sesion)
        references sesiones (id_sesion),
    constraint fk_asistencias_estudiante foreign key (id_estudiante)
        references estudiantes (id_estudiante),
    constraint fk_asistencias_acceso     foreign key (id_acceso)
        references accesos (id_acceso),
    constraint ck_asistencias_estado     check (estado in
        ('presente', 'tardanza', 'falta'))
) tablespace ts_acceso_log;

-- SEGURIDAD
-- hora_desde y hora_hasta usan formato HH24:MI
create table permisos_zona (
    id_permiso    number generated by default as identity (start with 1000),
    tipo_persona  varchar2(15) not null,
    id_zona       number(4)    not null,
    hora_desde    varchar2(5)  not null,
    hora_hasta    varchar2(5)  not null,
    constraint pk_permisos_zona      primary key (id_permiso),
    constraint fk_permisos_zona_zona foreign key (id_zona)
        references zonas (id_zona),
    constraint uq_permisos_zona      unique (tipo_persona, id_zona),
    constraint ck_permisos_tipo      check (tipo_persona in
        ('estudiante', 'docente', 'vigilante', 'administrativo')),
    constraint ck_permisos_desde     check (regexp_like(hora_desde,
        '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    constraint ck_permisos_hasta     check (regexp_like(hora_hasta,
        '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    constraint ck_permisos_rango     check (hora_desde <= hora_hasta)
);

